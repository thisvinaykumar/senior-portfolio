export type NodeKind = "step" | "money" | "ok" | "fail" | "aside";
export type Pt = [number, number];

export interface BpNode {
  id: string;
  x: number; // centre
  y: number; // centre
  h?: number;
  kind: NodeKind;
  title: string;
  sub: string;
  lines?: string[]; // extra lines for tall nodes
  detail: string[];
}

export interface BpEdge {
  id: string;
  points: Pt[];
  label?: { text: string; x: number; y: number; anchor?: "start" | "middle" | "end" };
  dashed?: boolean;
}

export interface BpScenario {
  id: string;
  label: string;
  tone: "cyan" | "amber" | "green" | "rose";
  summary: string;
  route: Pt[]; // the packet's path, through node centres
  edges: string[]; // edges lit while this scenario runs
  steps: string[]; // node ids in order — the phone layout lists these
}

export interface BpTradeoff {
  chose: string;
  over: string;
  why: string;
  cost: string;
}

export interface BpFlow {
  id: string;
  org: string; // where it was built: EasyRes or OpsX
  tab: string;
  title: string;
  lead: string;
  height: number;
  nodes: BpNode[];
  edges: BpEdge[];
  scenarios: BpScenario[];
  tradeoffs: BpTradeoff[];
}

